function createMockDirectModelProvider(
  id: string,
  opts?: {
    local?: boolean;
    health?: ProviderHealth['status'];
    fastChat?: boolean;
    models?: ModelCatalogSnapshot['models'];
  }
): ModelCatalogProvider {
  const fastChat = opts?.fastChat ?? true;
  const caps: BrainCapabilities = {
    streaming: true,
    fastChat,
    reasoning: true,
    coding: false,
    toolUse: false,
    multimodal: false,
    vision: false,
    webResearch: false,
    longContext: false,
    local: opts?.local ?? false
  };

  const modelId = `${id}-fast-model`;
  const catalog: ModelCatalogSnapshot = {
    providerId: id,
    models: opts?.models ?? [
      {
        id: modelId,
        providerId: id,
        displayName: `${id} Fast Model`,
        status: 'available',
        latencyClass: 'interactive',
        qualityClass: 'fast',
        costClass: 'low',
        contextClass: 'standard',
        privacyClass: opts?.local ? 'local_only' : 'standard_cloud',
        capabilities: { ...caps }
      }
    ],
    refreshedAt: Date.now()
  };

  const descriptor: ProviderDescriptor = {
    id,
    kind: 'model_provider',
    displayName: `${id} Direct Provider`,
    accessPath: opts?.local ? 'local_runtime' : 'official_api',
    capabilities: caps,
    health: { status: opts?.health ?? 'healthy', checkedAt: Date.now() },
    defaultModelId: modelId
  };

  return {
    id,
    getCapabilities: () => caps,
    health: async () => ({ status: opts?.health ?? 'healthy', checkedAt: Date.now() }),
    getCatalog: async () => catalog,
    getDescriptor: () => descriptor,
    async *chat(req: BrainRequest, options?: BrainRequestOptions): AsyncIterable<BrainEvent> {
      yield { type: 'started', requestId: req.requestId, providerId: id, modelId: options?.modelId };
      yield { type: 'delta', requestId: req.requestId, text: `Answer from ${id} with ${options?.modelId}` };
      yield { type: 'completed', requestId: req.requestId, text: 'Done' };
    }
  };
}

function createMockAgentRuntime(
  id: string,
  opts?: { health?: ProviderHealth['status']; onChat?: (req: BrainRequest, opts?: BrainRequestOptions) => void }
): BrainProvider {
  const caps: BrainCapabilities = {
    streaming: true,
    fastChat: false,
    reasoning: true,
    coding: true,
    toolUse: true,
    multimodal: false,
    vision: false,
    webResearch: false,
    longContext: true,
    local: false
  };

  return {
    id,
    getCapabilities: () => caps,
    health: async () => ({ status: opts?.health ?? 'healthy', checkedAt: Date.now() }),
    async *chat(req: BrainRequest, options?: BrainRequestOptions): AsyncIterable<BrainEvent> {
      opts?.onChat?.(req, options);
      yield { type: 'started', requestId: req.requestId, providerId: id, modelId: options?.modelId };
      yield { type: 'delta', requestId: req.requestId, text: `Generated by ${id}` };
      yield { type: 'completed', requestId: req.requestId, text: 'Done' };
    }
  };
}

